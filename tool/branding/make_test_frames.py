"""Writes tool/mock_server/test_clip_frames.dart: a few small JPEG frames
the mock server stitches into a Motion-JPEG test video (no FFmpeg needed).

Run from the project root:  python tool/branding/make_test_frames.py
"""
import base64
import io
import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
FONT = os.path.join(ROOT, 'assets', 'fonts', 'Inter-ExtraBold.ttf')
W, H = 320, 180
COLOURS = [(255, 51, 71), (255, 170, 0), (60, 200, 90), (40, 140, 255), (160, 80, 255), (230, 230, 230)]

frames = []
big = ImageFont.truetype(FONT, 34)
small = ImageFont.truetype(FONT, 14)
for i, col in enumerate(COLOURS):
    im = Image.new('RGB', (W, H), (12, 12, 16))
    d = ImageDraw.Draw(im)
    d.rectangle([0, H - 18, int(W * (i + 1) / len(COLOURS)), H], fill=col)
    d.text((W // 2, 70), 'Lumen test clip', font=big, fill=col, anchor='mm')
    d.text((W // 2, 120), f'frame {i + 1} of {len(COLOURS)}', font=small, fill=(200, 200, 200), anchor='mm')
    b = io.BytesIO()
    im.save(b, 'JPEG', quality=60)
    frames.append(base64.b64encode(b.getvalue()).decode())

out = os.path.join(ROOT, 'tool', 'mock_server', 'test_clip_frames.dart')
with open(out, 'w', encoding='utf-8', newline='\n') as fh:
    fh.write('// Generated by tool/branding/make_test_frames.py. Do not edit.\n')
    fh.write('// 320x180 JPEG frames for the mock server\'s test clip.\n\n')
    fh.write('const testClipWidth = %d;\nconst testClipHeight = %d;\n\n' % (W, H))
    fh.write('const testClipFrames = <String>[\n')
    for f in frames:
        fh.write("  '%s',\n" % f)
    fh.write('];\n')
print(out, sum(len(f) for f in frames))
